//! Compiles the Slint UI, after generating `theme.slint` from the Rust
//! design tokens.
//!
//! The tokens module is compiled into this build script by path rather than
//! through a dependency on `dbhive-ui-model`: that crate depends on
//! `dbhive-core` and every database driver, which a build script would then
//! have to compile a second time just to read some colours.

#[path = "../dbhive-ui-model/src/tokens.rs"]
#[allow(dead_code)]
mod tokens;

use std::fmt::Write;

fn kebab(name: &str) -> String {
    name.replace('_', "-")
}

fn generate_theme() -> String {
    let dark = tokens::fields(&tokens::DARK);
    let light = tokens::fields(&tokens::LIGHT);

    let mut s = String::new();
    s.push_str(
        "// GENERATED by build.rs from dbhive-ui-model/src/tokens.rs. Do not edit;\n\
         // change the tokens instead, where the contrast tests guard them.\n\n\
         export global Theme {\n\
         \x20   in-out property <bool> dark: true;\n\n",
    );
    // The user's accent colour (Settings > Appearance) replaces the three
    // primary tokens when set. Everything in the kit reads `Theme.primary`,
    // so one override restyles the whole app. The editor preferences ride
    // along so the SQL editor can read them without a prop chain through
    // every screen.
    s.push_str(
        "    // Runtime preferences, set from Rust (Settings).\n\
         \x20   in-out property <bool> accent-custom: false;\n\
         \x20   in-out property <color> accent-custom-color: transparent;\n\
         \x20   in-out property <color> accent-custom-foreground: transparent;\n\
         \x20   in-out property <length> editor-font-size: 13px;\n\
         \x20   in-out property <bool> editor-line-numbers: true;\n\n\
         \x20   // Drop shadow under dialogs.\n\
         \x20   out property <color> shadow: #00000070;\n\
         \x20   // Dims what sits behind a dialog stacked on another dialog.\n\
         \x20   out property <color> scrim: #00000080;\n\n",
    );
    for ((name, d), (_, l)) in dark.iter().zip(light.iter()) {
        let per_mode = format!("root.dark ? {} : {}", d.hex(), l.hex());
        let expr = match *name {
            "primary" => format!("root.accent-custom ? root.accent-custom-color : ({})", per_mode),
            "primary_foreground" => format!(
                "root.accent-custom ? root.accent-custom-foreground : ({})",
                per_mode
            ),
            "primary_soft" => format!(
                "root.accent-custom ? root.accent-custom-color.transparentize(0.85) : ({})",
                per_mode
            ),
            _ => per_mode,
        };
        let _ = writeln!(s, "    out property <color> {}: {};", kebab(name), expr);
    }
    s.push('\n');
    for (name, v) in [
        ("control", tokens::radius::CONTROL),
        ("card", tokens::radius::CARD),
        ("window", tokens::radius::WINDOW),
        ("pill", tokens::radius::PILL),
    ] {
        let _ = writeln!(s, "    out property <length> radius-{}: {}px;", name, v);
    }
    s.push('\n');
    for (name, v) in [
        ("display", tokens::size::DISPLAY),
        ("heading", tokens::size::HEADING),
        ("subheading", tokens::size::SUBHEADING),
        ("body", tokens::size::BODY),
        ("label", tokens::size::LABEL),
        ("small", tokens::size::SMALL),
        ("mono", tokens::size::MONO),
    ] {
        let _ = writeln!(s, "    out property <length> size-{}: {}px;", name, v);
    }
    s.push_str("}\n");
    s
}

/// One image property per SVG in `ui/icons`, so an icon is referenced as
/// `Icons.database` and a typo is a compile error rather than a blank box.
fn generate_icons(manifest_dir: &std::path::Path) -> String {
    let dir = manifest_dir.join("ui").join("icons");
    let mut names: Vec<String> = std::fs::read_dir(&dir)
        .expect("ui/icons")
        .filter_map(|e| e.ok())
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".svg"))
        .collect();
    names.sort();

    let mut s = String::from(
        "// GENERATED by build.rs from ui/icons/*.svg (Lucide, ISC licence).\n\
         // Add an icon by dropping its SVG into ui/icons.\n\n\
         export global Icons {\n",
    );
    for n in names {
        let stem = n.trim_end_matches(".svg");
        let path = dir.join(&n);
        let _ = writeln!(
            s,
            "    out property <image> {}: @image-url(\"{}\");",
            stem,
            path.display()
        );
    }
    s.push_str("}\n");
    s
}

/// slint_build emits `rerun-if-changed` for every file it reads, including
/// these generated ones. Cargo compares them against the build start time,
/// so rewriting them unconditionally made the script rerun on every check.
fn write_if_changed(path: &std::path::Path, contents: &str) {
    if std::fs::read_to_string(path).ok().as_deref() != Some(contents) {
        std::fs::write(path, contents).unwrap();
    }
}

fn main() {
    println!("cargo:rerun-if-changed=../dbhive-ui-model/src/tokens.rs");
    println!("cargo:rerun-if-changed=ui");

    let out_dir = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let generated = out_dir.join("generated");
    std::fs::create_dir_all(&generated).unwrap();
    write_if_changed(&generated.join("theme.slint"), &generate_theme());
    let manifest_dir = std::path::PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    write_if_changed(&generated.join("icons.slint"), &generate_icons(&manifest_dir));

    let config =
        slint_build::CompilerConfiguration::new().with_include_paths(vec![generated]);
    slint_build::compile_with_config("ui/app.slint", config)
        .expect("Slint UI failed to compile");
}
